"""意图判定：区分「医学问诊」与「会话语义」（确认 / 寒暄 / 感谢 / 收尾）

为什么需要它
------------
检索链路有个隐含假设：每一轮输入都是一个"待检索的问题"。但真实对话里
用户常常只回一句「好的」。没有这道闸门时会发生什么：

    「好的」 → 上下文改写（结合病史补全成病症查询）
             → 混合检索 + 精排（无条件返回 Top-5 疾病资料）
             → MEDICAL_PROMPT 规则「只能基于资料作答」
             → 又把上一个病的科普讲了一遍

所以判定要放在链路最前面，见 graph.node_classify_intent。

设计取舍
--------
1. **纯规则，不调 LLM**。这个判断不需要世界知识，而每加一次 LLM 调用
   就是每轮 +1~2s 延迟。规则兜不住时**一律判为 medical**——宁可多检索
   一次，也不要把真问题挡在检索之外（漏答比多答贵得多）。
2. **与 agents/source_router 分工不同**：router 判"该查哪类资料"，
   本模块判"要不要查"。两者互不依赖。
3. 词表是刻意留的扩展点，按真实对话慢慢补。补错方向只会多走一次检索，
   不影响回答正确性。

依赖：settings.intent_chat_max_chars（见 config.py）。
"""
import re

from .config import settings

# 纯确认 / 寒暄 / 感谢 / 收尾。单独出现时一定是会话语，不是问诊。
_ACK_WORDS: frozenset[str] = frozenset({
    # 确认
    "好", "好的", "好滴", "好哒", "好嘞", "行", "行吧", "可以", "没问题",
    "嗯", "嗯嗯", "恩", "对", "对的", "是的", "是", "有道理",
    "收到", "明白", "明白了", "懂了", "知道了", "了解", "了解了",
    # 寒暄 / 感谢
    # 「谢谢你 / 感谢你」要单列：_is_pure_ack 是"吃干净"判据，吃剩的「你」
    # 既不是确认词也不是语气助词，于是 `谢谢` 命中之后整串仍然吃不完 →
    # 判 False 落到医学分支，对一句致谢去检索作答（与"不了"同类缺陷）。
    # 不能把「你」塞进 _TAIL_CHARS —— 它不是语气助词，会把「好你」之类也放行。
    "你好", "您好", "hi", "hello", "在吗", "谢谢", "谢了", "感谢", "多谢",
    "谢谢你", "感谢你",
    "辛苦了", "麻烦你了", "你是谁",
    "ok", "okay", "okey", "sure", "thanks",
    # 收尾
    # 2026-09-25 补 "不了" / "算了" / "不必了"：词表原先只有「没了 / 没有了 /
    # 不用了 / 不需要」，独独漏了口语里最常用的「不了」。后果在真实对话里
    # 抓到了现行 —— 会话 56 消息 153：助手问「还有其他想了解的吗？」，
    # 用户回「不了」，规则门判 False 放行到医学分支，于是检索 + 生成了
    # 一段带 [1] 引用和「⚠️ 不能替代执业医师诊断」声明的科普，
    # 答非所问。这类"收尾"表达是封闭集合，直接补词表比等 LLM 兜底划算。
    "不了", "算了", "不必了", "不用",
    "再见", "拜拜", "先这样", "就这样", "没了", "没有了", "不用了", "不需要",
    "继续", "然后呢", "还有呢", "接着说",
})

# 命中任一即认为涉及医学内容或明确提问，绝不判为会话语。
# 必须放在词表之前判，否则「好的，那要吃多久药」这类会被误伤成会话语。
_MEDICAL_HINTS: tuple[str, ...] = (
    # 症状
    "痛", "疼", "痒", "烧", "发热", "咳", "痰", "吐", "呕", "泻", "拉肚",
    "晕", "肿", "麻", "乏", "累", "出血", "过敏", "炎", "癌", "病",
    # 2026-09-22 补：原表缺这几个，于是「好恶心 / 好困 / 好难受 / 好胀」
    # 既没命中线索、又满足「含确认词」，被规则门当附和放行（实测 4/4 中招）。
    # 「好痛 / 好痒 / 好晕 / 好累」之所以没出事，只是因为线索表里恰好有
    # 痛/痒/晕/累 —— 说明缺的是**结构性兜底**，见 _is_pure_ack。
    "恶心", "困", "难受", "胀",
    # 诊疗
    "药", "吃", "喝", "服", "剂量", "片", "针", "手术", "治", "查", "检",
    "化验", "指标", "血压", "血糖", "血", "尿", "便", "科", "医", "院",
    # 提问
    "怎么", "怎样", "如何", "为什么", "为啥", "多久", "多少", "几天",
    "要不要", "能不能", "可不可以", "是不是", "有没有", "严重", "要紧",
    "?", "？",
)

# 比对前先剥掉标点 / 空白 / 括号
_STRIP_RE = re.compile(r"[\s，。、！？~～,.!?…·\-—_\"'“”（）()【】\[\]]+")

# 尾部语气助词 / 填充字：扒掉之后剩下的若正好是确认词，仍算附和。
#   "好的呀" -> "好的"   "行了" -> "行"
_TAIL_CHARS: frozenset[str] = frozenset("呀啊吧了啦哦哟滴哒嘞嘛哈嗯噢喔咯噜叭的呐呢嘻诶哎诶")

# 贪心匹配要用长词优先，否则「好的好的」会被「好」逐字拆着走。
_ACK_SORTED: tuple[str, ...] = tuple(sorted(_ACK_WORDS, key=len, reverse=True))


def _normalize(text: str) -> str:
    return _STRIP_RE.sub("", (text or "").strip()).lower()


def _is_pure_ack(q: str) -> bool:
    """整串是否能被「确认词 + 语气助词」**吃干净**（允许任意顺序、任意重复）。

    这是本模块唯一一处结构性判据，用来替代原先的 `w in q` 子串匹配。
    旧写法的问题在于单字确认词（好 / 行 / 对 / 是 / 嗯 / 恩）做了**前缀**匹配：

        "好"     -> True    ✅ 附和
        "好痛"   -> True    ❌ 症状描述，被当成"好"+语气词
        "好恶心" -> True    ❌ 同上

    「好痛」没暴露只是因为线索表里恰好有「痛」；换成表里没有的症状词就中招。
    改成"吃干净"判据后，剩下的字符必须是**真正的语气助词**：

        "好" / "好的" / "好的呀" / "好的好的" / "行了" / "行，知道了" -> True
        "好痛" / "好恶心" / "好困" / "好难受" / "好嗜睡"              -> False

    消费顺序是从前往后、优先吃确认词（`_ACK_SORTED` 长词优先），吃不动才吃
    语气助词。**不能只从尾部剥语气词**——「行，知道了」会先剥掉"了"变成
    "知道"，而"知道"不在词表里，整串就吃不完了（实测踩过）。

    代价是带前缀的说法（「我明白了」「改天聊，拜拜」）不再判 True（旧写法
    靠子串匹配接住它们）。这是**有意的取舍**：它们落到第二层 LLM 分类，
    node_rewrite 拿到 act=ack 后不产出 enhanced_query、不触发检索，
    代价是每轮多一次本来就要发的 LLM 调用；而 True 的覆盖面越小越安全
    ——第一层一旦假阳性，第二层**根本没机会纠正**。
    """
    if q in _ACK_WORDS:
        return True
    rest = q
    while rest:
        hit = next((w for w in _ACK_SORTED if rest.startswith(w)), None)
        if hit is not None:          # 优先级 1：确认词
            rest = rest[len(hit):]
        elif rest[0] in _TAIL_CHARS:  # 优先级 2：语气助词
            rest = rest[1:]
        else:
            return False
    return True


def is_conversational(text: str) -> bool:
    """这轮发言是否**不构成医疗问诊**（可安全跳过检索）。

    只有确定是会话发言才返回 True；任何拿不准的情况都返回 False，
    交回医学路径处理（漏答比多答贵）。

        示例：
          "好的"              -> True
          "嗯嗯"              -> True
          "好的呀"            -> True
          "好的，那要吃多久药"  -> False   （命中"药"）
          "高血压能吃党参吗"    -> False   （命中"血压"/"吃"）
          "好的我明天去医院"    -> False   （命中"医"/"院"）
          "好恶心"            -> False   （症状，不是"好"+语气词）
    """
    q = _normalize(text)
    if not q:
        return False
    # 太长的一定不是单纯附和
    if len(q) > settings.intent_chat_max_chars:
        return False
    # 整串字面就是已知附和词 ——  unambiguous，优先放行。
    # 必须排在线索检查之前：「麻烦你了」含「麻」（发麻症状线索），
    # 否则它会因为"命中症状字"被永久短路，词表里写它也白写。
    if q in _ACK_WORDS:
        return True
    # 含医学线索 / 疑问词的，一律不算会话语
    if any(h in q for h in _MEDICAL_HINTS):
        return False
    # 整串由确认词 + 语气助词拼成，才算附和
    return _is_pure_ack(q)
